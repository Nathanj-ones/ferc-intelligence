#!/usr/bin/env python3
"""
Migrate a pre-repair staging database to the 8 September repair schema.

    python3 migrations/001_repair_2026_09_08.py --db staging/operating_assets.sqlite
    python3 migrations/001_repair_2026_09_08.py --db ... --apply     # actually write

WHY THIS EXISTS

`schema.sql` is applied with `CREATE TABLE IF NOT EXISTS`, which does exactly
nothing to a table that already exists. The repair added two tables and fifteen
columns, so a database built before that moment opens and then fails on first
use with a bare `no such column: slot_state` -- naming neither the table nor the
remedy. w1-runtime hit this for real on their own test databases.

The repair is additive by construction. Every change here is a `CREATE TABLE IF
NOT EXISTS` or an `ALTER TABLE ... ADD COLUMN`; nothing is dropped, renamed,
retyped or rewritten, so no stored value can be lost by running it. It is still
DRY BY DEFAULT: it prints the plan and changes nothing unless `--apply` is given,
because a migration that runs itself is a migration nobody read.

WHAT IT DELIBERATELY DOES NOT DO

It does not backfill the new columns. `source_health`, `due_date` and the rest
describe an obligation calendar that only a run can compute; inventing values
for them would be exactly the fabrication the repair contract forbids. After
migrating, re-run coverage. Rows written before the migration carry NULL in the
new columns, and NULL here honestly means "this run predates the calendar",
which is different from any value we could make up.

Nor does it touch `observations`. The A04 unit correction changes DERIVED values
(a margin becomes percent-valued), and a derived value is regenerated by re-
running its adapter, not patched in place. Patching would leave the value
changed and its lineage, method and observation id describing the old
computation. See `--report-a04`, which tells you what a re-run will move.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sqlite3
import sys

HERE = pathlib.Path(__file__).resolve().parent
PKG = HERE.parent
sys.path.insert(0, str(PKG))

#: (table, column, type) -- every one additive, every one nullable
ADD_COLUMNS = [
    ("coverage_expected", "due_date", "TEXT"),
    ("coverage_expected", "slot_state", "TEXT"),
    ("coverage_expected", "obligation_form", "TEXT"),
    ("coverage_expected", "obligation_authority", "TEXT"),
    ("coverage_expected", "obligation_evidence_kind", "TEXT"),
    ("coverage_expected", "source_health", "TEXT"),
    ("coverage_expected", "source_health_detail", "TEXT"),
    ("coverage_expected", "denominator_origin", "TEXT"),
    ("coverage_expected", "docket", "TEXT"),
    ("coverage_expected", "facility", "TEXT"),
    ("coverage_expected", "shipped_requirement", "TEXT"),
    ("coverage_measured", "candidates_refused", "INTEGER NOT NULL DEFAULT 0"),
    ("coverage_measured", "refusal_gates", "TEXT"),
    ("lineage_edges", "input_population_id", "TEXT"),
    # A07: readiness measured within the field's own template, with the counts
    # it was derived from so the verdict can be re-checked.
    ("field_status", "adapter_implemented", "INTEGER"),
    ("field_status", "has_data_in_template", "INTEGER"),
    ("field_status", "validated_in_template", "INTEGER"),
    ("field_status", "within_template_observations", "INTEGER"),
    ("field_status", "within_template_present", "INTEGER"),
    ("field_status", "within_template_present_pass", "INTEGER"),
    ("field_status", "within_template_entities", "INTEGER"),
    ("field_status", "within_template_regimes", "TEXT"),
    ("field_status", "selector_failures_in_template", "INTEGER"),
    ("field_status", "core_slots_in_template", "INTEGER"),
    ("field_status", "cross_template_present_pass", "INTEGER"),
]

NEW_TABLES = ("lineage_populations", "observation_versions")

NEW_INDEXES = [
    ("ix_expected_state", "CREATE INDEX IF NOT EXISTS ix_expected_state "
                          "ON coverage_expected(slot_state, source_health)"),
    ("ix_lineage_pop_obs", "CREATE INDEX IF NOT EXISTS ix_lineage_pop_obs "
                           "ON lineage_populations(observation_id)"),
    ("ix_obsver_filing", "CREATE INDEX IF NOT EXISTS ix_obsver_filing "
                         "ON observation_versions(source_system, filing_id)"),
]


def columns(con, table: str) -> set[str]:
    try:
        return {r[1] for r in con.execute(f"PRAGMA table_info({table})")}
    except sqlite3.Error:
        return set()


def tables(con) -> set[str]:
    return {r[0] for r in con.execute(
        "SELECT name FROM sqlite_master WHERE type='table'")}


def plan(con) -> dict:
    have_tables = tables(con)
    missing_tables = [t for t in NEW_TABLES if t not in have_tables]
    missing_cols = []
    for table, col, decl in ADD_COLUMNS:
        if table not in have_tables:
            continue                      # created wholesale by schema.sql
        if col not in columns(con, table):
            missing_cols.append((table, col, decl))
    return {"missing_tables": missing_tables, "missing_columns": missing_cols,
            "already_current": not missing_tables and not missing_cols}


def a04_report(con) -> dict:
    """What a re-run will move, so the change is expected rather than surprising.

    Reported, never patched. A margin stored as 0.432043 under unit `percent` is
    a DERIVED value; the repair makes the derivation emit 43.204338, and the way
    to get that is to re-run the adapter, which also rewrites the lineage and the
    method that explain it.
    """
    out = {}
    try:
        out["margins_stored_as_fraction"] = con.execute(
            "SELECT COUNT(*) FROM observations WHERE metric_id LIKE '%margin_pct' "
            "AND availability='present' AND value_num IS NOT NULL "
            "AND ABS(value_num) <= 1.0").fetchone()[0]
        out["revenue_per_barrel_undimensioned"] = con.execute(
            "SELECT COUNT(*) FROM observations WHERE metric_id LIKE '%per_barrel' "
            "AND availability='present' AND unit IN ('','ratio')").fetchone()[0]
        out["oil_index_dangling"] = con.execute(
            "SELECT COUNT(*) FROM observations WHERE metric_id='liq_oil_price_index'"
        ).fetchone()[0]
    except sqlite3.Error as exc:
        out["error"] = f"{type(exc).__name__}: {exc}"
    out["remedy"] = ("re-run the adapters; these are derived values and are corrected "
                     "by regeneration, not by an UPDATE that would leave the value "
                     "changed while its lineage still describes the old computation")
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--db", required=True)
    ap.add_argument("--apply", action="store_true",
                    help="actually write; without it nothing is changed")
    ap.add_argument("--report-a04", action="store_true",
                    help="also report what an adapter re-run will move")
    args = ap.parse_args(argv)

    db = pathlib.Path(args.db)
    if not db.is_file():
        print(f"no database at {db}", file=sys.stderr)
        return 1

    con = sqlite3.connect(db)
    try:
        p = plan(con)
        print(f"database : {db}")
        print(f"tables   : {len(tables(con))}")
        if p["already_current"]:
            print("\nalready at the repair schema; nothing to do")
        else:
            print(f"\nMISSING TABLES  ({len(p['missing_tables'])}): "
                  f"{', '.join(p['missing_tables']) or 'none'}")
            print(f"MISSING COLUMNS ({len(p['missing_columns'])}):")
            for t, c, d in p["missing_columns"]:
                print(f"   ALTER TABLE {t} ADD COLUMN {c} {d};")

        if args.report_a04:
            print("\nwhat an adapter re-run will move (reported, not patched):")
            for k, v in a04_report(con).items():
                print(f"   {k:36s} {v}")

        if not args.apply:
            print("\nDRY RUN -- nothing was written. Re-run with --apply to migrate.")
            return 0

        if p["already_current"]:
            return 0

        # ORDER MATTERS, and getting it wrong fails loudly rather than halfway.
        # `schema.sql` creates an index over `coverage_expected(slot_state, ...)`,
        # so running it before the ALTERs raises `no such column: slot_state` --
        # the very error this migration exists to remove. Columns first, then the
        # script for the new tables and their indexes.
        added = []
        for t, c, d in p["missing_columns"]:
            con.execute(f"ALTER TABLE {t} ADD COLUMN {c} {d}")
            added.append(f"{t}.{c}")
        schema = (PKG / "ferclib" / "schema.sql").read_text(encoding="utf-8")
        con.executescript(schema)        # creates only what does not already exist
        for _name, sql in NEW_INDEXES:
            try:
                con.execute(sql)
            except sqlite3.Error as exc:
                print(f"   index skipped: {type(exc).__name__}: {exc}")
        con.commit()

        after = plan(con)
        ok = after["already_current"]
        print(f"\napplied: {len(added)} column(s), "
              f"{len(p['missing_tables'])} table(s)")
        for a in added:
            print(f"   + {a}")
        print(f"verification: schema is {'CURRENT' if ok else 'STILL INCOMPLETE'}")
        (PKG / "verification").mkdir(exist_ok=True)
        (PKG / "verification" / "migration_001.json").write_text(json.dumps({
            "database": str(db), "added_columns": added,
            "created_tables": p["missing_tables"],
            "verified_current": ok,
            "note": ("additive only: no column dropped, renamed, retyped or "
                     "rewritten. New columns are NULL on pre-existing rows, which "
                     "honestly means 'this run predates the calendar'. Re-run "
                     "coverage to populate them."),
        }, indent=1), encoding="utf-8")
        return 0 if ok else 1
    finally:
        con.close()


if __name__ == "__main__":
    sys.exit(main())
